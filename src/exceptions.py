"""Модуль с пользовательскими исключениями для магазина."""


class ZeroQuantityError(Exception):
    """Исключение для обработки событий добавления товара с нулевым количеством.

    Вызывается при попытке добавить в категорию или заказ товар,
    у которого количество равно нулю.
    """

    def __init__(self, message: str = "Товар с нулевым количеством не может быть добавлен"):
        """Инициализация исключения.

        :param message: Сообщение об ошибке
        """
        super().__init__(message)
        self.message = message

    def __str__(self) -> str:
        """Возвращает строковое представление исключения."""
        return self.message
